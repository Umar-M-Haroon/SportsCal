    //MARK: - Push-to-Start Registration (install-ID keyed)
    //
    // One Redis record per install. APNS token rotation just overwrites the
    // install's record — no orphan keys can shadow the new token. Per the
    // historical bug: previously each `PushToStart-{token}` and
    // `PushToStartEvents-{token}` could outlive a rotated token for 24h and
    // both the old and new tokens would receive push-to-start for the same
    // game, spawning two Live Activities on the device.
    writeRoutes.post("pushToStart", "register") { req async throws -> HTTPStatus in
        let registration = try req.content.decode(PushToStartRegistration.self)
        let environment = resolveAPNSEnvironment(from: req)
        let isSandbox = environment == .sandbox
        let installID = resolveInstallID(from: req, fallbackToken: registration.token)

        let install = PushToStartInstall(
            installID: installID,
            token: registration.token,
            favorites: registration.favorites,
            eventIDs: registration.eventIDs ?? [],
            environment: environment
        )

        // If this install previously held a different token, drop the reverse
        // index pointing at it so a stale-token cleanup later won't blow away
        // the live install.
        let installKey = RedisEndpoint.pushToStartByInstall(installID).getValue(isDebug: isSandbox).rawValue
        if let existing = try? await req.kv.getJSON(installKey, as: PushToStartInstall.self),
           existing.token != registration.token {
            let staleIndex = RedisEndpoint.pushToStartTokenIndex(existing.token).getValue(isDebug: isSandbox).rawValue
            _ = try? await req.kv.delete([staleIndex])
            // Same install, new token → ActivityKit rotated the push-to-start token.
            // Surface it so we can watch rotation frequency (it determines how often
            // a long-TTL registration would otherwise go stale before a refresh).
            req.logger.info("Push-to-start token rotated for install \(installID.prefix(8))... [\(environment.rawValue)] (\(existing.token.prefix(8))... → \(registration.token.prefix(8))...)")
            await req.telemetry.warning("pushtostart.token_rotated", [
                "install": String(installID.prefix(8)),
                "env": environment.rawValue,
            ])
        }

        let indexKey = RedisEndpoint.pushToStartTokenIndex(registration.token).getValue(isDebug: isSandbox).rawValue
        do {
            try await req.kv.setJSON(installKey, value: install, ttl: PushToStartInstall.registrationTTL)
            try await req.kv.setString(indexKey, value: installID, ttl: PushToStartInstall.registrationTTL)
        } catch {
            // Capture before rethrowing: a failed persist here means the device
            // can never receive a push-to-start, and it used to vanish silently.
            await req.telemetry.error("pushtostart.register.failed", [
                "install": String(installID.prefix(8)),
                "env": environment.rawValue,
                "error": "\(error)",
            ])
            throw error
        }

        req.logger.info("Registered push-to-start install \(installID.prefix(8))... [\(environment.rawValue)] favorites=\(registration.favorites.count) eventIDs=\(install.eventIDs.count)")
        await req.telemetry.info("pushtostart.registered", [
            "install": String(installID.prefix(8)),
            "env": environment.rawValue,
            "favorites": "\(registration.favorites.count)",
            "events": "\(install.eventIDs.count)",
        ])

        // Push-to-start is otherwise transition-only: the scheduled job fires when a
        // game flips to "in". A user who follows a match that is ALREADY live (or
        // taps "Follow World Cup" mid-match) would get nothing until the next
        // kickoff. Kick off Live Activities for any followed games that are live
        // right now. Deduped against the transition path via the shared
        // SentPushToStart-{token}-{eventID} claim, so this never double-fires.
        if req.application.storage[APNSConfiguredKey.self] == true {
            let serverIsDebug = req.application.environment == .development
            let liveKey = RedisEndpoint.ESPN.latestLiveInfo.getValue(isDebug: serverIsDebug).rawValue
            if let liveScore = try? await req.kv.getJSON(liveKey, as: LiveScore.self) {
                await ESPNFetchJob.sendStartsForAlreadyLiveGames(
                    install: install,
                    liveGames: ESPNFetchJob.collectAllGamesFromLiveScore(liveScore),
                    environment: environment,
                    kv: req.kv,
                    apns: req.application.apnsSending,
                    clock: req.application.appClock,
                    isDebug: serverIsDebug,
                    logger: req.logger,
                    metrics: req.application.pushMetrics,
                    telemetry: req.application.telemetry
                )
            }
        }
        return .ok
    }

