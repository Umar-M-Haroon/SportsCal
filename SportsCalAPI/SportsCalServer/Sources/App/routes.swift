        let body = try req.content.decode(DeregisterRequest.self)
        let environment = resolveAPNSEnvironment(from: req)
        let isSandbox = environment == .sandbox
        let installID = resolveInstallID(from: req, fallbackToken: body.token)

        let installKey = RedisEndpoint.pushToStartByInstall(installID).getValue(isDebug: isSandbox).rawValue
        let indexKey = RedisEndpoint.pushToStartTokenIndex(body.token).getValue(isDebug: isSandbox).rawValue
        var keysToDelete = [installKey, indexKey]
        // SentPushToStart-{token}-{eventID} markers are per-event; scan to find them all.
        let sentPattern = (isSandbox ? "debug-SentPushToStart-" : "SentPushToStart-") + body.token + "-*"
        let sentKeys = (try? await req.kv.scanKeys(matching: sentPattern)) ?? []
        keysToDelete.append(contentsOf: sentKeys)
        let deleted = (try? await req.kv.delete(keysToDelete)) ?? 0
        req.logger.info("Deregistered push-to-start install \(installID.prefix(8))... [\(environment.rawValue)] — removed \(deleted) keys (\(sentKeys.count) sent-markers)")
        return .ok
    }

