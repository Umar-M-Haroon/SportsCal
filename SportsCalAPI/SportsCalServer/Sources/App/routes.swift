/// In-process last-known-good cache for near-static payloads served straight
/// from Redis. A transient Redis failure (timeout, pool exhaustion, dropped
/// connection) on the `/teams` read was rethrowing as HTTP 500 — Sentry
/// `SPORTS-CAL-38` logged 356 of these across 7 users, and the app reads an
/// empty/failed teams fetch as "no games / unknown team" (see the ★1 review).
/// Teams data changes rarely, so serving the last good payload turns those
/// blips into a slightly-stale success instead of a hard failure.
actor LastKnownGoodCache {
    static let shared = LastKnownGoodCache()
    private var teams: String?
    func storeTeams(_ value: String) { teams = value }
    var teamsValue: String? { teams }
}

/// Resolve which APNS gateway issued the device token in this request. The iOS
/// client signals it via the `X-APNS-Env: sandbox|production` header so the
/// hint stays out of URLs and access logs. Older clients that don't send the
/// header fall back to the server's own environment for back-compat — this
/// matches the prior single-environment behavior on a per-server basis.
func resolveAPNSEnvironment(from req: Request) -> APNSEnvironment {
    if let raw = req.headers.first(name: "X-APNS-Env"),
       let env = APNSEnvironment(rawValue: raw) {
        return env
    }
    return req.application.environment == .development ? .sandbox : .production
}

/// Per-install stable identifier (UUID generated by the app on first launch,
/// persisted in Keychain). All push-to-start state is keyed by this so an APNS
/// token rotation doesn't leave a duplicate registration shadowing the new one.
/// Falls back to the supplied push token (legacy clients pre-install-id header)
/// so any duplicate it causes is at worst self-inflicted from a single device.
func resolveInstallID(from req: Request, fallbackToken: String) -> String {
    if let raw = req.headers.first(name: "X-Install-ID"), !raw.isEmpty {
        return raw
    }
    return "legacy-\(fallbackToken)"
}

func routes(_ app: Application) throws {
    // Register API version middleware globally
    app.middleware.use(APIVersionMiddleware())

    // MARK: - Unauthenticated ping
    // Cheap reachability probe used by the iOS app to auto-pick between local,
    // dev (Tailscale), and prod servers. Must stay outside rate limiting and
    // API-key middleware so HEAD requests from the env picker are free.
    app.get("ping") { _ in "pong" }
    app.on(.HEAD, "ping") { _ in HTTPStatus.ok }

    // MARK: - Development-only routes (log streaming)
    if app.environment == .development {
        // Log Streaming WebSocket
        app.webSocket("ws", "logs") { req, ws async in
            await LogBroadcaster.shared.addSubscriber(ws)

            // `ws.onText`'s setter asserts it runs on the connection's event loop, but this async
            // closure executes in a detached Task off the loop — register on `ws.eventLoop`.
            ws.eventLoop.execute {
            ws.onText { ws, text in
                // Parse filter commands from client
                guard let data = text.data(using: .utf8),
                      let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
                      let type = json["type"] as? String, type == "filter" else {
                    return
                }

                var filter = LogFilter()

                if let levelStr = json["level"] as? String,
                   let level = Logger.Level(levelStr) {
                    filter.minLevel = level
                }

                if let labels = json["labels"] as? [String], !labels.isEmpty {
                    filter.labels = Set(labels)
                }

                if let search = json["search"] as? String, !search.isEmpty {
                    filter.searchText = search
                }

                Task {
                    await LogBroadcaster.shared.updateSubscriberFilter(ws, filter: filter)
                }
            }
            }

            // Keep alive until disconnect
            try? await ws.onClose.get()
            await LogBroadcaster.shared.removeSubscriber(ws)
        }
    }

    // MARK: - Admin Routes
    // Gated by ADMIN_API_KEY_HASH in every environment. AdminKeyMiddleware fails
    // closed if the env var is unset, so registering these unconditionally is safe.
    let adminRoutes = app.grouped(AdminKeyMiddleware())
    try adminRoutes.register(collection: AdminController())
    try adminRoutes.register(collection: ParityController())

    // MARK: - Versioned Routes (v2025)
    // Rate limit runs before the API key check so unauthed floods get 429'd
    // after the threshold instead of costing one Redis hit per 403.
    let v2025 = app.grouped(RateLimitMiddleware(limit: 300, windowSeconds: 60, keyPrefix: "rl:v2025"))
        .grouped("v2025")
        .grouped(APIKeyMiddleware())
    registerAPIRoutes(on: v2025, app: app)

    // MARK: - Legacy Routes (unversioned)
    // Keep for backward compatibility with older app versions
    let legacy = app.grouped(RateLimitMiddleware(limit: 300, windowSeconds: 60, keyPrefix: "rl:legacy"))
        .grouped(APIKeyMiddleware())
    registerAPIRoutes(on: legacy, app: app)

    // MARK: - Universal Links (public, unauthenticated)
    // Serves the apple-app-site-association at the well-known path with the
    // correct content type and NO redirect, so iOS validates `applinks:` for
    // shared game + World Cup bracket links. appID = <TeamID>.<BundleID>.
    // NOTE: requires the link host's DNS to point here + the Associated Domains
    // entitlement on the app before universal links resolve to the app.
    app.get(".well-known", "apple-app-site-association") { _ async -> Response in
        let json = """
        {"applinks":{"apps":[],"details":[{"appID":"9GDU5ZNHX7.com.KomodoLLC.SportsCal","paths":["/g/*","/wc/*"]}]}}
        """
        var headers = HTTPHeaders()
        headers.contentType = .json
        return Response(status: .ok, headers: headers, body: .init(string: json))
    }

    // Web fallback for recipients without the app: a tiny page that shows the
    // App Store smart banner and bounces to the listing. When the app IS
    // installed, iOS opens it directly (universal link) and never renders this.
    let appStoreURL = "https://apps.apple.com/app/id1580232928"
    func appStoreFallback(_ title: String) -> Response {
        let html = """
        <!doctype html><html><head><meta charset="utf-8">
        <meta name="viewport" content="width=device-width, initial-scale=1">
        <meta name="apple-itunes-app" content="app-id=1580232928">
        <title>\(title) · Scoreline</title>
        <meta http-equiv="refresh" content="0; url=\(appStoreURL)">
        </head><body><p>Opening Scoreline… <a href="\(appStoreURL)">Get the app</a>.</p></body></html>
        """
        var headers = HTTPHeaders()
        headers.contentType = .html
        return Response(status: .ok, headers: headers, body: .init(string: html))
    }
    app.get("g", ":id") { _ async -> Response in appStoreFallback("Game") }
    app.get("wc", "bracket") { _ async -> Response in appStoreFallback("World Cup Bracket") }
}

/// Registers all API routes on a given route builder.
/// This allows the same routes to be registered under both versioned and legacy paths.
private func registerAPIRoutes(on routes: RoutesBuilder, app: Application) {
    // Tighter limit for endpoints that mutate Redis state — the app API key is
    // embedded in every binary and extractable, so a leaked key shouldn't be
    // able to flood Redis with garbage registrations.
    let writeRoutes = routes.grouped(RateLimitMiddleware(limit: 20, windowSeconds: 60, keyPrefix: "rl:write"))

    // MARK: - Client Telemetry
    // Lightweight ingestion for client-side funnel events (paywall_shown,
    // gate_hit, purchase_completed, activation_*). Namespaced `client.<event>` and
    // fed into the same Telemetry composite as server events, so they land in the
    // Redis per-day counters (admin-viewable) and structured logs for free.
    // Fail-open by construction: a malformed body, unknown event, or oversized
    // field must never surface an error to the client's fire-and-forget call.
    // Mounted on `routes` (300/min) rather than `writeRoutes` (20/min) because
    // these are user-paced and higher-frequency than registrations.
    routes.post("telemetry") { req async throws -> HTTPStatus in
        guard let payload = try? req.content.decode(ClientTelemetryEvent.self),
              ClientTelemetryEvent.allowedEvents.contains(payload.event) else {
            return .ok
        }
        // Bound field cardinality/size so a leaked key can't bloat log/counter keys.
        var fields = (payload.fields ?? [:]).filter { $0.key.count <= 32 && $0.value.count <= 64 }
        if let install = req.headers.first(name: "X-Install-ID") {
            fields["install"] = String(install.prefix(8))
        }
        await req.telemetry.info("client.\(payload.event)", fields)
        return .ok
    }

    //MARK: - Schedules
    // The schedule is already stored in Redis as JSON (written via setJSON). Return
    // the cached string verbatim instead of decoding it into a LiveScore and
    // re-encoding it on every request — that round-trip burned ~5s of CPU per call
    // (the dominant TTFB cost) and is pure waste since the bytes are identical.
    routes.get("schedules") { req async throws -> String in
        let key = RedisEndpoint.ESPN.latestSchedule.getValue(isDebug: req.application.environment == .development).rawValue
        guard let raw = try await req.kv.getString(key), !raw.isEmpty else {
            throw NetworkError.invalidData
        }
        return raw
    }

    //MARK: - Sport
    routes.get("sport", ":sport") { req in
        let sport = SportType(rawValue: req.parameters.get("sport")!)
        let schedule = try await req.kv.getJSON(RedisEndpoint.ESPN.latestSchedule.getValue(isDebug: req.application.environment == .development).rawValue, as: LiveScore.self)
        let result: LiveEvent?
        switch sport {
        case .basketball:
            guard let nba = schedule?.nba else { throw Abort(.badRequest) }
            result = nba
        case .soccer:
            guard let soccer = schedule?.soccer else { throw Abort(.badRequest) }
            result = soccer
        case .hockey:
            guard let nhl = schedule?.nhl else { throw Abort(.badRequest) }
            result = nhl
        case .mlb:
            guard let mlb = schedule?.mlb else { throw Abort(.badRequest) }
            result = mlb
        case .nfl:
            guard let nfl = schedule?.nfl else { throw Abort(.badRequest) }
            result = nfl
        case .golf:
            guard let golf = schedule?.golf else { throw Abort(.badRequest) }
            result = golf
        case .tennis:
            guard let tennis = schedule?.tennis else { throw Abort(.badRequest) }
            result = tennis
        case .racing:
            guard let racing = schedule?.racing else { throw Abort(.badRequest) }
            result = racing
        case .none:
            throw Abort(.badRequest)
        }
        if let res = result {
            return encodeResult(res: res)
        } else {
            throw Abort(.badRequest)
        }
    }

    //MARK: - On-demand schedule for a specific day
    // The cached /schedules blob only spans the recent/upcoming window. This
    // endpoint fetches every ESPN league's scoreboard for an arbitrary day
    // (path param `date` = YYYYMMDD) and returns a merged LiveScore, so the
    // client can browse multi-sport schedules far outside that window. Results
    // are cached per-day (past days are immutable → long TTL).
    routes.get("schedules", "date", ":date") { req async throws -> String in
        guard let dateStr = req.parameters.get("date"),
              dateStr.count == 8, let dateInt = Int(dateStr) else {
            throw Abort(.badRequest)
        }
        let isDebug = req.application.environment == .development
        let cacheKey = "ESPN Schedule Date \(dateInt)\(isDebug ? " DEBUG" : "")"
        if let cached = try? await req.kv.getString(cacheKey), !cached.isEmpty {
            return cached
        }
        let liveScore = await buildESPNScheduleForDate(dateInt: dateInt, client: req.client)
        let json = encodeResult(res: liveScore)

        let fmt = DateFormatter()
        fmt.dateFormat = "yyyyMMdd"
        fmt.timeZone = TimeZone(identifier: "America/New_York")
        let todayInt = Int(fmt.string(from: Date())) ?? dateInt
        let ttl: TimeInterval = dateInt < todayInt ? 86_400 : 600
        try? await req.kv.setString(cacheKey, value: json, ttl: ttl)
        return json
    }

    //MARK: - Teams
    // Same as /schedules: serve the cached JSON string directly rather than
    // decoding to [Team] and re-encoding it per request.
    routes.get("teams") { req async throws -> String in
        let key = RedisEndpoint.teams.getValue(isDebug: req.application.environment == .development).rawValue
        do {
            let value = (try await req.kv.getString(key)) ?? "[]"
            // Only cache real payloads — never let an empty result poison the
            // fallback (that would re-create the "no teams" failure mode).
            if value != "[]" { await LastKnownGoodCache.shared.storeTeams(value) }
            return value
        } catch {
            if let cached = await LastKnownGoodCache.shared.teamsValue {
                req.logger.warning("teams: Redis read failed, serving last-known-good — \(String(reflecting: error))")
                return cached
            }
            throw error
        }
    }

    //MARK: - Play-by-Play (per-event)
    // Three-tier lookup: (1) Redis hot cache for live/in-progress games, (2) SQLite archive
    // for finalized games, (3) on-demand ESPN fetch using the `ESPN-Event-Map` or query params.
    routes.get("plays", ":eventID") { req async throws -> String in
        guard let eventID = req.parameters.get("eventID"), !eventID.isEmpty else {
            throw Abort(.badRequest)
        }
        let sport = try? req.query.get(String.self, at: "sport")
        let league = try? req.query.get(String.self, at: "league")
        guard let cached = try await PlayResolver.resolve(
            req: req, eventID: eventID, sport: sport, league: league
        ) else {
            throw Abort(.notFound)
        }
        return encodeResult(res: cached)
    }

    //MARK: - Live Websocket
    routes.webSocket("ws") { req, ws async in
        let isDebug = req.application.environment == .development
        var lastSentHash: Int? = nil

        while !ws.isClosed {
            do {
                // Check if there are live or upcoming games before pushing data
                let hasGames = await Integrator.hasLiveOrUpcomingGames(
                    redis: req.application.redis,
                    isDebug: isDebug
                )

                if hasGames {
                    // Serve the cached JSON string verbatim instead of decoding to
                    // LiveScore and re-encoding it — same waste the /schedules fix
                    // removed, but here it ran every 5s per connected client. The
                    // stored bytes are identical to what encodeResult would produce.
                    let key = RedisEndpoint.ESPN.latestLiveInfo.getValue(isDebug: isDebug).rawValue
                    let stringResult = (try await req.kv.getString(key)) ?? "{}"

                    // Only send if data actually changed (avoids redundant multi-MB pushes)
                    let currentHash = stringResult.hashValue
                    if currentHash != lastSentHash {
                        // Observability: the live frame outgrew the old 4 MB client
                        // cap (~4.76 MB seen). WebSocket frames bypass Caddy's gzip,
                        // so they ship uncompressed — log the size to track the
                        // culprit and confirm it stays within the client's 16 MB cap.
                        let bytes = stringResult.utf8.count
                        if bytes > 3_000_000 {
                            req.logger.warning("Large live WS frame", metadata: ["bytes": "\(bytes)"])
                        }
                        try await ws.send(stringResult)
                        lastSentHash = currentHash
                    }

                    try await Task.sleep(nanoseconds: 5_000_000_000) // 5s when live
                } else {
                    // No live games — sleep longer and send lightweight heartbeat
                    lastSentHash = nil
                    try await ws.send("{}")
                    try await Task.sleep(nanoseconds: 60_000_000_000) // 60s when idle
                }
            } catch {
                req.logger.error("WebSocket live score push failed", metadata: ["error": "\(error)"])
                break
            }
        }
    }

    //MARK: - all-live-games
    routes.get("all-live-games") { req async throws -> String in
        let liveScore = try await req.kv.getJSON(RedisEndpoint.ESPN.latestFullLiveInfo.getValue(isDebug: req.application.environment == .development).rawValue, as: LiveScore.self)
        return encodeResult(res: liveScore)
    }

    //MARK: DEBUG
    if app.environment == .development {
        //MARK: - livedebug websocket
        routes.webSocket("livedebug") { req, ws async in
            while !ws.isClosed {
                do {
                    var directory = req.application.directory.workingDirectory
                    directory.append("/LiveTest.json")
                    let fileURL = URL(fileURLWithPath: directory)
                    var jsonScore = try JSONDecoder().decode(LiveScore.self, from: Data(contentsOf: fileURL))
                    
                    
                    let newEvents: [Game] = jsonScore.soccer?.events
                        .compactMap({ game -> Game in
                            let newHomeScore = "\(Int.random(in: 1...5))"
                            let newAwayScore = "\(Int.random(in: 1...5))"
                            // Only include essential fields - strSport/strLeague are computed from idLeague
                            return Game(idLiveScore: game.idLiveScore, idEvent: game.idEvent, strSport: nil, idLeague: game.idLeague, strLeague: nil, idHomeTeam: game.idHomeTeam, idAwayTeam: game.idAwayTeam, strHomeTeam: game.strHomeTeam, strAwayTeam: game.strAwayTeam, strHomeTeamBadge: game.strHomeTeamBadge, strAwayTeamBadge: game.strAwayTeamBadge, intHomeScore: newHomeScore, intAwayScore: newAwayScore, strPlayer: nil, idPlayer: nil, intEventScore: nil, intEventScoreTotal: nil, strStatus: game.strStatus, strProgress: game.strProgress, strEventTime: nil, dateEvent: nil, updated: nil, strTimestamp: game.strTimestamp, isoDate: nil)

                        }) ?? []
                    jsonScore.soccer?.events = newEvents
                    try await Task.sleep(nanoseconds: 5000000000)
                    let stringResult = encodeResult(res: jsonScore)
                    try await ws.send(stringResult)
                } catch {
                    req.logger.error("Debug WebSocket live score push failed", metadata: ["error": "\(error)"])
                }
            }
        }

        //MARK: - replay (developer "replay a game as live")
        // The client connects, sends the selected `Game` shell as the first text frame,
        // and the server streams reconstructed `LiveScore` frames from that game's recorded
        // play-by-play, paced by `?speed=` (frames-per-second, default 8). Dev-only.
        // maxFrameSize is bumped well past the 16 KB default: the client's first frame carries
        // the full play-by-play array (often 100 KB–1 MB), which the default would reject.
        routes.webSocket("replay", ":eventID", maxFrameSize: .init(integerLiteral: 8 * 1024 * 1024)) { req, ws async in
            let eventID = req.parameters.get("eventID") ?? ""
            let speed = min(max((try? req.query.get(Double.self, at: "speed")) ?? 8.0, 0.1), 5000)

            // Await the game shell (first inbound text frame), with a timeout fallback so a
            // silent client doesn't leak the connection. The async `webSocket` closure runs in a
            // detached Task (off the connection's event loop), but `ws.onText`'s setter is guarded
            // by `preconditionInEventLoop()` — so we must register it on `ws.eventLoop`. Registering
            // onText + scheduleTask on the same loop also keeps the `fired` guard race-free.
            final class Once { var fired = false }
            let once = Once()
            let shellText: String? = await withCheckedContinuation { (cont: CheckedContinuation<String?, Never>) in
                ws.eventLoop.execute {
                    ws.onText { _, text in
                        guard !once.fired else { return }
                        once.fired = true
                        cont.resume(returning: text)
                    }
                    ws.eventLoop.scheduleTask(in: .seconds(15)) {
                        guard !once.fired else { return }
                        once.fired = true
                        cont.resume(returning: nil)
                    }
                }
            }

            // The handshake carries the shell and (optionally) client-fetched plays. Fall back
            // to a bare `Game` for older clients.
            let handshake: ReplayHandshake?
            let shell: Game?
            if let shellText, let shellData = shellText.data(using: .utf8) {
                handshake = try? JSONDecoder().decode(ReplayHandshake.self, from: shellData)
                shell = handshake?.shell ?? (try? JSONDecoder().decode(Game.self, from: shellData))
            } else {
                handshake = nil
                shell = nil
            }
            guard let shell, let slot = ReplayDriver.slot(for: shell) else {
                try? await ws.send(#"{"error":"replay: missing or unsupported game shell"}"#)
                try? await ws.close()
                return
            }

            // Prefer client-supplied plays; otherwise resolve them server-side.
            var plays = handshake?.plays ?? []
            if plays.isEmpty {
                let espn = ReplayDriver.espnSportLeague(for: shell)
                plays = (try? await PlayResolver.resolve(
                    req: req, eventID: eventID, sport: espn?.sport, league: espn?.league
                ))?.plays ?? []
            }
            guard !plays.isEmpty else {
                try? await ws.send(#"{"error":"replay: no play-by-play available for this game"}"#)
                try? await ws.close()
                return
            }

            req.logger.info("Replay starting for \(eventID): \(plays.count) plays at \(speed)x")
            let frames = ReplayDriver.snapshots(shell: shell, plays: plays, slot: slot)
            let delayNanos = UInt64((1_000_000_000.0 / speed).rounded())
            for frame in frames {
                if ws.isClosed { break }
                try? await ws.send(encodeResult(res: frame))
                try? await Task.sleep(nanoseconds: delayNanos)
            }
            req.logger.info("Replay finished for \(eventID)")
        }

        //MARK: - live-debug
        routes.get("live-debug") { req async throws in
            var directory = req.application.directory.workingDirectory
            directory.append("/MockLive.json")
            let fileURL = URL(fileURLWithPath: directory)
            let jsonScore = try JSONDecoder().decode(LiveScore.self, from: Data(contentsOf: fileURL))
            let stringResult = encodeResult(res: jsonScore)
            return stringResult
        }

        //MARK: - Debug Push-to-Start Trigger
        routes.post("debug", "trigger-push-to-start") { req async throws -> String in
            struct DebugTriggerRequest: Content {
                var eventID: String
                var homeTeam: String
                var awayTeam: String
            }

            let body = try req.content.decode(DebugTriggerRequest.self)
            let apnsConfigured = req.application.storage[APNSConfiguredKey.self] ?? false

            // Iterate both prod and sandbox install keyspaces so a single dev
            // server can dispatch tests to both Xcode dev devices and TestFlight
            // tokens.
            let envSpecs: [(prefix: String, env: APNSEnvironment)] = [
                ("PushToStartByInstall-", .production),
                ("debug-PushToStartByInstall-", .sandbox),
            ]

            // Build diagnostic trace
            var trace: [String] = []
            trace.append("env=\(req.application.environment.name)")
            trace.append("apnsConfigured=\(apnsConfigured)")
            trace.append("triggerEventID=\(body.eventID)")
            trace.append("triggerHome=\(body.homeTeam)")
            trace.append("triggerAway=\(body.awayTeam)")

            var allInstalls: [(install: PushToStartInstall, env: APNSEnvironment)] = []
            for spec in envSpecs {
                let pattern = "\(spec.prefix)*"
                let scanned = (try? await req.application.redis.send(command: "keys", with: [pattern.convertedToRESPValue()])
                    .array?
                    .compactMap({ $0.string })) ?? []
                trace.append("\(spec.env.rawValue) installs=\(scanned.count)")
                for key in scanned {
                    if let install = try? await req.kv.getJSON(key, as: PushToStartInstall.self) {
                        allInstalls.append((install, spec.env))
                    }
                }
            }
            trace.append("totalInstalls=\(allInstalls.count)")

            guard !allInstalls.isEmpty else {
                let traceStr = trace.joined(separator: "\n")
                let result: [String: Any] = ["notified": 0, "tokens": [] as [String], "reason": "no_registrations", "trace": traceStr]
                let data = try JSONSerialization.data(withJSONObject: result)
                return String(data: data, encoding: .utf8)!
            }

            guard apnsConfigured else {
                let traceStr = trace.joined(separator: "\n")
                let result: [String: Any] = ["notified": 0, "tokens": [] as [String], "reason": "apns_not_configured", "trace": traceStr]
                let data = try JSONSerialization.data(withJSONObject: result)
                return String(data: data, encoding: .utf8)!
            }

            let prodClient = await req.application.apns.client(.production)
            let sandboxClient = await req.application.apns.client(.development)
            var notifiedTokens: [String] = []
            var errors: [String] = []

            for entry in allInstalls {
                let install = entry.install
                let token = install.token

                let favoritesMatch = install.favorites.contains(where: { $0 == body.homeTeam || $0 == body.awayTeam })
                let eventMatch = install.eventIDs.contains(body.eventID)

                trace.append("install=\(install.installID.prefix(8))... token=\(token.prefix(12))... [\(entry.env.rawValue)] favorites=\(install.favorites) eventIDs=\(install.eventIDs) favMatch=\(favoritesMatch) eventMatch=\(eventMatch)")

                guard favoritesMatch || eventMatch else { continue }

                let attributes = LiveSportAttributes(
                    homeTeam: body.homeTeam,
                    awayTeam: body.awayTeam,
                    eventID: body.eventID
                )
                let contentState = ContentState(
                    homeScore: 12,
                    awayScore: 9,
                    status: "in",
                    progress: "4:20 - 1st",
                    lastPlay: nil
                )

                do {
                    let notification = APNSStartLiveActivityNotification(
                        expiration: .immediately,
                        priority: .immediately,
                        appID: "com.KomodoLLC.SportsCal",
                        contentState: contentState,
                        timestamp: Int(Date().timeIntervalSince1970),
                        attributes: attributes,
                        attributesType: "LiveSportActivityAttributes",
                        alert: APNSAlertNotificationContent(
                            title: .raw("\(body.homeTeam) vs \(body.awayTeam)"),
                            body: .raw("Debug game is starting now!")
                        )
                    )
                    let client = entry.env == .sandbox ? sandboxClient : prodClient
                    try await client.sendStartLiveActivityNotification(
                        notification,
                        deviceToken: token,
                        collapseID: body.eventID
                    )
                    notifiedTokens.append(String(token.prefix(12)) + "...")
                    trace.append("SENT OK to \(token.prefix(12))... [\(entry.env.rawValue)]")
                } catch {
                    let errMsg = "\(error)"
                    errors.append("\(token.prefix(12))... [\(entry.env.rawValue)]: \(errMsg)")
                    trace.append("SEND FAILED \(token.prefix(12))... [\(entry.env.rawValue)]: \(errMsg)")
                    if let apnsError = error as? APNSError,
                       apnsError.reason == .badDeviceToken || apnsError.reason == .unregistered {
                        let isSandbox = entry.env == .sandbox
                        let installKey = RedisEndpoint.pushToStartByInstall(install.installID).getValue(isDebug: isSandbox).rawValue
